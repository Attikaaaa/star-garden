// ---------- Floors, rooms and rewards ----------
// COMPASS: the shops, treasure, wardens and the boss show on the map from the start.
function compassMark() {
  if (!G.floor || !teamHas('compass')) return;
  for (const r of G.floor.rooms) if (r.type !== 'normal' && r.type !== 'start') r.seen = true;
}
// A new land (main.js loadFloor): COZY QUILT heals, the WANDERER set hands out a potion,
// the LUCKY PIGGY pays interest on the team purse.
function itemFloorStart(depth) {
  compassMark();
  for (const p of G.players) {
    if (p.dead || p.down) continue;
    if (depth > 0 && p.quilt && p.hp < p.maxHp) healPlayer(p, 2);
    if (p.wander) addBelt(p, gpick(POTION_IDS));
  }
  if (depth > 0 && teamHas('piggy')) {
    const nest = teamHas('nest'), k = Math.min(nest ? 40 : 20, Math.floor(G.coins * (nest ? 0.2 : 0.1)));
    if (k > 0) { gainCoins(k); toast('LUCKY PIGGY: +' + k + ' COINS'); Audio_.sfx('coin'); }
  }
}
// A boss fell (main.js giveBossReward): the MAGIC BEAN grows.
function itemBossDown() {
  for (const p of G.players) {
    if (!p.bean || p.dead) continue;
    p.dmg += p.bean2 ? 1 : 0.5;
    say(p, 'THE BEAN GROWS!');
    burst(p.x, p.y - 10, 10, ['h', 'G', 'H'], 70, 0.5, { g: -30 });
  }
}
