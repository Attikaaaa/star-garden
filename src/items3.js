const _i3Belt = useBelt;
useBelt = function (p, i) {
  const kind = p.belt[i], n = p.belt.length;
  _i3Belt(p, i);
  if (p.lunch && kind && kind !== 'turret' && !POTIONS[kind].charm && p.belt.length < n && p.hp < p.maxHp) healPlayer(p, 1);
};

// ---------- Hitting harder ----------
// TEAM BANNER: a friend holding it stands close by.
function bannerNear(p) {
  if (G.players.length < 2) return false;
  for (const q of G.players) if (q !== p && q.banner && alive(q) && Math.hypot(q.x - p.x, q.y - p.y) < 80) return true;
  return false;
}
// FIRST STRIKE, HUNTER'S MARK, LAST STAND and the TEAM BANNER, on one hit of shot s on foe e.
const _i3Dmg = shotHitDmg;
shotHitDmg = function (s, e) {
  let d = _i3Dmg(s, e);
  const p = s.own;
  if (!p || !e) return d;
  if (p.opener) {
    if (!e.struck) e.struck = [];
    if (!e.struck.includes(p.pid)) { e.struck.push(p.pid); d *= 2; burst(s.x, s.y, 5, ['w', 'L', 'C'], 70, 0.25); }
  }
  if (p.hunter && (e.boss || e.elite || EDEF[e.type].warden)) d *= 1.3;
  if (p.grit && p.hp <= 2) d *= 1.5;
  if (bannerNear(p)) d *= 1.2;
  return d;
};
// FOCUS STONE: standing still for a moment charges the next shots (they fly cyan).
const FOCUS_T = 0.5;
const focused = (p) => p.focus && p.stillT >= FOCUS_T;
const _i3Tick = itemTick;
itemTick = function (p, dt) {
  _i3Tick(p, dt);
  if (!p.focus) return;
  const still = p.fx0 !== undefined && Math.abs(p.x - p.fx0) + Math.abs(p.y - p.fy0) < 0.05 && !(p.dashT > 0);
  const was = focused(p);
  p.fx0 = p.x; p.fy0 = p.y;
  p.stillT = still ? (p.stillT || 0) + dt : 0;
  if (!was && focused(p)) burst(p.x, p.y - 10, 6, ['c', 'C', 'w'], 50, 0.35, { g: -20 });
};
const _i3Shoot = playerShoot;
playerShoot = function (p, ax, ay) {
  if (!focused(p)) return _i3Shoot(p, ax, ay);
  const d = p.dmg, n = SHOTS.length;
  p.dmg = d * (p.steady ? 1.6 : 1.4);
  _i3Shoot(p, ax, ay);
  p.dmg = d;
  for (let i = n; i < SHOTS.length; i++) if (SHOTS[i].own === p && !SHOTS[i].tint) SHOTS[i].tint = 'c';
};

