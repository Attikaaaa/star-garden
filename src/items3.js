// ---------- Hearts, hits and helping up ----------
// A heart picked up (entities.js): HEART LOCKET doubles it, PICNIC BLANKET shares it.
function heartHeal(p, n) {
  healPlayer(p, p.locket ? n * 2 : n);
  if (p.picnic) for (const q of G.players) if (q !== p && alive(q) && q.hp < q.maxHp) healPlayer(q, 1);
}
